import {test,expect,beforeAll,afterAll} from 'vitest';
import {Pool} from 'pg';
import {randomUUID} from 'node:crypto';
import {Client} from '@colyseus/sdk';
import {AccountService} from '../../apps/server/src/accounts/service';
import {PostgresRoomRepository} from '../../apps/server/src/storage/postgres-room';
import {startServer} from '../../apps/server/src/server';
const pool=new Pool({connectionString:process.env.TEST_DATABASE_URL??'postgres://coedit:coedit_local_only@127.0.0.1:54329/coedit'});
const accounts=new AccountService(pool),repository=new PostgresRoomRepository(pool);
let server:Awaited<ReturnType<typeof startServer>>;let actor:string;const roomIds:string[]=[];
beforeAll(async()=>{await accounts.migrate();await repository.migrate();server=await startServer(0,false,{accounts,repository});});
afterAll(async()=>{await server.close();for(const id of roomIds)await pool.query('DELETE FROM coedit_rooms WHERE id=$1',[id]);if(actor)await pool.query('DELETE FROM coedit_teachers WHERE id=$1',[actor]);await pool.end();});
const post=async(path:string,body:unknown,token?:string)=>fetch(server.url+'/api'+path,{method:'POST',headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:JSON.stringify(body)});
test('HTTP classroom flow and two student logins preserve server-owned identity and scene',async()=>{
  const registered=await post('/teachers/register',{username:'http-'+randomUUID(),password:'test-password-1234'});expect(registered.status).toBe(201);
  const teacher=await registered.json();actor=teacher.actor;
  const classroom=await (await post('/classes',{name:'반',roomCount:6},teacher.token)).json();roomIds.push(...classroom.rooms.map((r:any)=>r.id));
  const students=await (await post('/classes/'+classroom.id+'/students',{count:30},teacher.token)).json();expect(students).toHaveLength(30);
  const login=async()=> (await post('/students/login',{roomCode:students[0].roomCode,issuedId:students[0].issuedId})).json();
  const identity=await login();const client=new Client(server.url);
  let room=await client.joinOrCreate('studio',{token:identity.token,roomKey:identity.roomKey});room.onMessage('*',()=>{});
  const response=new Promise<any>(resolve=>room.onMessage('result',resolve));
  room.send('command',{actor:identity.actor,source:'gizmo',requestId:'place',ops:[{op:'place',id:'mine',assetId:'chair',position:[1,0,0]}]});
  expect((await response).result.ok).toBe(true);await room.leave();
  const again=await login();expect(again.actor).toBe(identity.actor);
  room=await client.joinOrCreate('studio',{token:again.token,roomKey:again.roomKey});room.onMessage('*',()=>{});
  const snapshot=new Promise<any>(resolve=>room.onMessage('event',e=>{if(e.type==='snapshot')resolve(e.snapshot);}));room.send('sync');
  expect((await snapshot).objects.mine.owner).toBe(identity.actor);
  expect((await post('/classes',{name:'forged',roomCount:1,role:'teacher'},again.token)).status).toBe(403);
  await room.leave();
});
